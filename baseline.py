"""Задача 3 — Baseline: поиск документов по совпадению слов."""

from preprocess import preprocess  # предобработка текста из задачи 2

# =====================================================================
# =======================ЕРМОЛАЕВ ЕГОР=================================
# =====================================================================
# baseline_search - простой поиск: чем больше слов запроса есть в документе, тем выше документ в выдаче.
#
# ЧТО ПРИНИМАЕТ
#   query : str
#       Текст запроса «как есть».
#   doc_tokens : dict[str, list[str]]
#       Уже обработанные документы: {doc_id: [токены документа]}.
#       Это результат preprocess(текст_документа, config) для каждого
#       документа. Списки для 4 задачи
#       ВАЖНО: doc_tokens должны быть построены под ТОТ ЖЕ config,
#       что передан в эту функцию, иначе слова запроса и документов
#       не совпадут.
#   config : str
#       Одна из конфигураций предобработки: "A", "B", "C" или "D"
#   top_k : int = 5
#       Сколько лучших документов вернуть.
#   metric : str = "coverage"
#       Как считать оценку. Сейчас поддерживается только "coverage".
#
# ЧТО ВОЗВРАЩАЕТ
#   list[tuple[str, float]] - список пар (doc_id, score), не длиннее top_k.
#     * score = |Q ∩ D| / |Q| - доля слов запроса, которые нашлись
#       в документе (от 0 до 1);
#     * порядок: score по убыванию, при равенстве - по doc_id;
#     * документы без единого совпадения в список не попадают;
#     * пустой запрос даёт [].
# =====================================================================


def baseline_search(
    query: str,                        # текст запроса
    doc_tokens: dict[str, list[str]],  # {doc_id: список токенов}
    config: str,                       # "A" / "B" / "C" / "D"
    top_k: int = 5,                    # сколько документов вернуть
    metric: str = "coverage",          # способ подсчёта оценки
) -> list[tuple[str, float]]:          # [(doc_id, score), ...]
    """
    Ищет документы по совпадению слов с запросом (см. описание выше).
    """

    # Q множество слов запроса
    # |Q ∩ D| / |Q| каждое слово считается один раз
    # preprocess применяем ТОЛЬКО к запросу: документы уже обработаны заранее и пришли готовыми в doc_tokens
    q = set(preprocess(query, config))

    # Пустой запрос: искать нечего (делить на |Q| = 0 нельзя)
    if not q:
        return []

    results = []  # сюда складываем пары (doc_id, score)

    for doc_id, tokens in doc_tokens.items():
        # Слова запроса, которые есть в документе, Q ∩ D.
        # intersection сам принимает список, поэтому превращать tokens во множество не нужно,
        #  а сам doc_tokens остаётся неизменным
        common = q.intersection(tokens)

        # Документы без единого совпадения в выдачу не включаем.
        if common:
            score = len(common) / len(q)  # coverage = |Q ∩ D| / |Q|
            results.append((doc_id, score))

    # results это список пар (doc_id, score)
    # Сортировка: сначала больший score (минус делает порядок убывающим), 
    # при равных score - по doc_id по возрастанию.
    results.sort(key=lambda pair: (-pair[1], pair[0]))

    # Оставляем только top_k лучших.
    return results[:top_k]